        in
        base8 +
        if byte >= 128 then 7
        else if byte >= 64 then 6
        else if byte >= 32 then 5
        else if byte >= 16 then 4
        else if byte >= 8 then 3
        else if byte >= 4 then 2
        else if byte >= 2 then 1
        else 0

      let mask_through offset =
        if offset = word_mask then -1
        else (1 lsl (offset + 1)) - 1

      (* Find the greatest set index strictly below [limit] at [level], or [-1].
          The sentinel keeps maximum removal allocation-free. *)
      let rec find_before queue level limit =
        if limit <= 0 then -1
        else
          let last = limit - 1 in
          let word_index = last lsr word_shift in
          let words = Array.unsafe_get queue.levels level in
          if word_index >= Array.length words then
            find_before queue level (Array.length words * word_bits)
          else
            let masked =
              Array.unsafe_get words word_index land
              mask_through (last land word_mask)
            in
            if masked <> 0 then
              (word_index * word_bits) + highest_bit masked
            else if level + 1 >= level_count then
              -1
            else
              let previous_word = find_before queue (level + 1) word_index in
              if previous_word < 0 then -1
              else
                let word = Array.unsafe_get words previous_word in
                (previous_word * word_bits) + highest_bit word

      let rec clear_index queue level index =
        let word_index = index lsr word_shift in
        let words = Array.unsafe_get queue.levels level in
        let previous = Array.unsafe_get words word_index in
        let bit = 1 lsl (index land word_mask) in
        let next = previous land lnot bit in
        Array.unsafe_set words word_index next;
        if next = 0 && level + 1 < level_count then
          clear_index queue (level + 1) word_index

      let[@inline always] remove_max queue =
        let maximum = queue.maximum in
        if maximum >= 0 then begin
          clear_index queue 0 maximum;
          queue.maximum <- find_before queue 0 maximum
        end

      let[@inline always] pop_max queue =
        let result = queue.maximum in
        if result < 0 then None
        else begin
          remove_max queue;
          Some result
        end
    end

    type queue = {
      heap : RankQueue.t;
      trace : trace;
      physically_queued : bool DynArray.t;
      side_dirty : bool DynArray.t;
      infos : rank_info DynArray.t;
      ranks : int VH.t;
      mutable next_rank : int;
    }

    let[@inline always] create_queue () =
      {
        heap = RankQueue.create ();
        trace = create_trace ();
        physically_queued = DynArray.create ();
        side_dirty = DynArray.create ();
        infos = DynArray.create ();
        ranks = VH.create 32;
        next_rank = 0;
      }

    let[@inline always] fresh_rank queue variable =
      let result = queue.next_rank in
      queue.next_rank <- result + 1;
      VH.replace queue.ranks variable result;
      DynArray.add queue.infos (make_rank_info variable);
      DynArray.add queue.physically_queued false;
      DynArray.add queue.side_dirty false;
      trace_node queue.trace result variable;
      result

    let[@inline always] rank queue variable =
      match VH.find_option queue.ranks variable with
      | Some result -> result
      | None -> fresh_rank queue variable

    let[@inline always] queue_insert queue variable =
      let variable_rank = rank queue variable in
      let info = DynArray.get queue.infos variable_rank in
      if not info.queued then begin
        info.variable <- variable;
        info.queued <- true;
        if not (DynArray.get queue.physically_queued variable_rank) then begin
          DynArray.set queue.physically_queued variable_rank true;
          RankQueue.add queue.heap variable_rank
        end;
        trace_queue queue.trace "push" variable_rank
      end

    let queue_defer_side_stabilization = false

    let[@inline always] queue_insert_side queue variable =
      queue_insert queue variable

    let queue_insert_readers queue _changed_rank readers =
      VH.iter (fun reader () -> queue_insert queue reader) readers

    let[@inline always] queue_force_side _queue _target_rank = false

    let[@inline always] queue_mark_side_dirty queue target_rank =
      DynArray.set queue.side_dirty target_rank true

    let[@inline always] queue_clear_side_dirty queue target_rank =
      DynArray.set queue.side_dirty target_rank false

    let[@inline always] queue_side_dirty queue target_rank =
      DynArray.get queue.side_dirty target_rank

    let[@inline always] queue_cancel queue target_rank =
      (DynArray.get queue.infos target_rank).queued <- false;
      queue_clear_side_dirty queue target_rank

    let[@inline always] finish_physical_pop queue result_rank =
      DynArray.set queue.physically_queued result_rank false;
      let info = DynArray.get queue.infos result_rank in
      if info.queued then begin
        info.queued <- false;
        trace_queue queue.trace "pop" result_rank;
        Some info.variable
      end else
        None

    let rec discard_cancelled_maxima queue =
      if not (RankQueue.is_empty queue.heap) then begin
        let maximum = RankQueue.get_max_elt queue.heap in
        if not (DynArray.get queue.infos maximum).queued then begin
          RankQueue.remove_max queue.heap;
          DynArray.set queue.physically_queued maximum false;
          discard_cancelled_maxima queue
        end
      end

    let[@inline always] queue_max_rank queue =
      discard_cancelled_maxima queue;
      if RankQueue.is_empty queue.heap then -1 else RankQueue.get_max_elt queue.heap

    let[@inline always] queue_remove_max queue result_rank =
      RankQueue.remove_max queue.heap;
      match finish_physical_pop queue result_rank with
      | Some variable -> variable
      | None -> assert false

    let rec queue_pop queue =
      match RankQueue.pop_max queue.heap with
      | None -> None
      | Some result_rank ->
        begin match finish_physical_pop queue result_rank with
          | Some variable -> Some variable
          | None -> queue_pop queue
        end

    let[@inline always] queue_note_evaluation _queue _owner_rank = ()
    let[@inline always] queue_enter_episode _queue = ()
    let[@inline always] queue_leave_episode _queue = ()

    let[@inline always] trace_get queue source_rank target_rank =
      match queue.trace with
      | TraceDisabled -> ()
      | TraceEnabled _ ->
        let selected = target_rank <= source_rank in
        let new_w =
          selected
          && not (DynArray.get queue.infos target_rank).controlled
        in
        trace_dependency queue.trace "get" source_rank target_rank
          (if selected then Some target_rank else None) new_w

    let[@inline always] trace_side queue source_rank target_rank =
      match queue.trace with
      | TraceDisabled -> ()
      | TraceEnabled _ ->
        let selected = source_rank <= target_rank in
        let new_w =
          selected
          && not (DynArray.get queue.infos source_rank).controlled
        in
        trace_dependency queue.trace "side" source_rank target_rank
          (if selected then Some source_rank else None) new_w

    let[@inline always] seed_started queue variable =
      match VH.find_option queue.ranks variable with
      | None -> false
      | Some variable_rank ->
        (DynArray.get queue.infos variable_rank).started

    (* Roots are discovered one at a time. Work reached from one seed is
        drained before the next seed can receive a rank. Starting-state
        variables which were not reached from a root are seeded afterward. *)
    let solve_initial queue is_started solve_episode roots starts =
      let seeds = roots @ List.map fst starts in
      match
        Control.solve_seeds_with_fuel Stdlib.max_int
          is_started
          (fun () -> queue_pop queue)
          solve_episode seeds
      with
      | Control.SeedsSolved _ -> ()
      | Control.SeedsOutOfFuel ->
        failwith "QSolver: exhausted max_int seed fuel"

    let finish_trace queue =
      match queue.trace with
      | TraceDisabled -> ()
      | TraceEnabled _ ->
        let w = ref 0 in
        DynArray.iter
          (fun info -> if info.controlled then incr w)
          queue.infos;
        trace_finish queue.trace (DynArray.length queue.infos) !w

    type state = {
      sigma : S.d VH.t;
      starts : S.d VH.t;
      (* A row contains readers accumulated before the variable receives a
          rank. Membership certifies an immediate pure-bottom RHS. *)
      dormant_bottom : set VH.t;
      side_cells : side_cell_row VH.t;
      mutable reset_at_close : reset_sources VH.t option;
      mutable last_targets : set VH.t option;
      queue : queue;
      mutable deferred_wakes : set option;
    }

    type episode = {
      owner : S.v;
      owner_rank : int;
      owner_info : rank_info;
      mutable owner_phase : U.phase;
      mutable outgoing_cells : side_cell_row option;
      mutable local_side : side_row option;
      mutable previous_targets : set option;
      mutable current_targets : set option;
      (* Minimum-ranked owner or dependency read in this evaluation. *)
      mutable min_scope : S.v * int;
    }

    let[@inline always] create_state () =
      {
        sigma = VH.create 32;
        starts = VH.create 16;
        dormant_bottom = VH.create 16;
        side_cells = VH.create 32;
        reset_at_close = None;
        last_targets = None;
        queue = create_queue ();
        deferred_wakes = None;
      }

    let[@inline always] get_or_create table key capacity =
      try VH.find table key with Not_found ->
        let row = VH.create capacity in
        VH.replace table key row;
        row

    let[@inline always] start_value state variable =
      VH.find_default state.starts variable bottom

    let[@inline always] materialize state variable =
      if not (VH.mem state.sigma variable) then
        VH.replace state.sigma variable bottom

    let[@inline always] lattice_equal left right =
      S.Dom.equal left right

    let[@inline always] side_update
        _source target phase old input aggregate =
      if not SidePolicy.reluctant then U.update true target phase old input
      else
        let next_phase, proposal = U.update_lazy true target phase old input in
        if S.Dom.leq input old then next_phase, proposal ()
        else if S.Dom.leq input aggregate then next_phase, S.Dom.join old input
        else next_phase, proposal ()

    (* Slots outlive phase resets and bottom-valued contributions. Initialize
       the tree on the first post-policy shrink, then refresh every written leaf. *)
    let reserve_slot target_info =
      if not Config.aggregate_cache then -1 else begin
        let cache = match target_info.aggregate_cache with
          | Some cache -> cache | None -> JoinTree.cache_empty in
        let slot, next = JoinTree.reserve_cache cache in
        target_info.aggregate_cache <- Some next;
        slot
      end

    let cached_aggregate state target target_info contributions cell old next =
      match target_info.aggregate_cache with
      | None -> None
      | Some cache ->
        let initial_values () =
          let values = Array.make cache.JoinTree.cache_capacity bottom in
          VH.fold (fun source contribution () ->
              let cell = VH.find (VH.find state.side_cells source) target in
              values.(cell.slot) <- contribution) contributions ();
          Array.to_list values in
        let cache, aggregate = JoinTree.refresh_cache cache cell.slot old next initial_values in
        target_info.aggregate_cache <- Some cache;
        aggregate

    let[@inline always] recompute_aggregate contributions =
      VH.fold
        (fun _ contribution result -> S.Dom.join contribution result)
        contributions bottom

    let[@inline always] enqueue state variable =
      queue_insert state.queue variable

    let[@inline always] enqueue_side state variable =
      queue_insert_side state.queue variable

    let[@inline always] readers_of_info info =
      match info.readers with
      | Some readers -> readers
      | None ->
        let readers = VH.create 4 in
        info.readers <- Some readers;
        readers

    (* Promotion is permanent. Any readers accumulated while the target was
        rankless move into its normal rank-local information. *)
    let[@inline always] activate_rank state variable =
      match VH.find_option state.queue.ranks variable with
      | Some variable_rank ->
        variable_rank,
        DynArray.get state.queue.infos variable_rank,
        false
      | None ->
        let dormant_readers =
          VH.find_option state.dormant_bottom variable
        in
        let variable_rank = fresh_rank state.queue variable in
        let info = DynArray.get state.queue.infos variable_rank in
        begin match dormant_readers with
          | None -> variable_rank, info, false
          | Some readers ->
            VH.remove state.dormant_bottom variable;
            info.readers <- Some readers;
            variable_rank, info, true
        end

    let[@inline always] mark_controlled
        dependent_info dependent_rank dependency_rank =
      if dependency_rank >= dependent_rank then
        dependent_info.controlled <- true

    let[@inline always] remove_registration state scope source target =
      match state.reset_at_close with
      | None -> ()
      | Some reset_at_close ->
        begin match VH.find_option reset_at_close scope with
          | None -> ()
          | Some sources ->
            begin match VH.find_option sources source with
              | None -> ()
              | Some targets ->
                VH.remove targets target;
                if VH.length targets = 0 then VH.remove sources source
            end;
            if VH.length sources = 0 then VH.remove reset_at_close scope
        end

    let[@inline always] add_registration state scope source target =
      match state.reset_at_close with
      | None ->
        let reset_at_close = VH.create 16 in
        state.reset_at_close <- Some reset_at_close;
        let sources = get_or_create reset_at_close scope 2 in
        let targets = get_or_create sources source 2 in
        VH.replace targets target ()
      | Some reset_at_close ->
        let sources = get_or_create reset_at_close scope 2 in
        let targets = get_or_create sources source 2 in
        VH.replace targets target ()

    let[@inline always] register_reset
        state source target target_rank scope scope_rank cell phase =
      if Features.side_effect_phase_reset then begin
        let requested =
          if scope_rank < target_rank then Some scope else None
        in
        let unchanged =
          match cell.reset_at, requested with
          | None, None -> true
          | Some old_scope, Some new_scope ->
            S.Var.equal old_scope new_scope
          | _ -> false
        in
        if not unchanged then begin
          begin match cell.reset_at with
            | Some previous ->
              remove_registration state previous source target
            | None -> ()
          end;
          begin match requested with
            | Some next -> add_registration state next source target
            | None -> ()
          end;
          cell.reset_at <- requested
        end
      end;
      cell.phase <- phase

    let[@inline always] reset_registered_cells state scope =
      if Features.side_effect_phase_reset then
        match state.reset_at_close with
        | None -> ()
        | Some reset_at_close ->
          match VH.find_option reset_at_close scope with
          | None -> ()
          | Some sources ->
            VH.iter
              (fun source targets ->
                 match VH.find_option state.side_cells source with
                 | None -> assert false
                 | Some cells ->
                   VH.iter
                     (fun target () ->
                        match VH.find_option cells target with
                        | None -> assert false
                        | Some cell ->
                          cell.phase <- U.initial_phase true target;
                          cell.reset_at <- None)
                     targets)
              sources;
            VH.remove reset_at_close scope

    let[@inline always] write_changed_value
        state owner_rank owner_info owner value =
      VH.replace state.sigma owner value;
      trace_value state.queue.trace owner_rank true;
      begin match owner_info.readers with
        | None -> ()
        | Some readers ->
          queue_insert_readers state.queue owner_rank readers;
          VH.clear readers
      end
    let[@inline always] defer_readers state readers =
      let deferred =
        match state.deferred_wakes with
        | Some deferred -> deferred
        | None ->
          let deferred = VH.create 4 in
          state.deferred_wakes <- Some deferred;
          deferred
      in
      VH.iter (fun reader () -> VH.replace deferred reader ()) readers

    let[@inline always] flush_deferred state =
      match state.deferred_wakes with
      | None -> ()
      | Some deferred ->
        queue_insert_readers state.queue (-1) deferred;
        VH.clear deferred

    let[@inline always] write_dirty_value
        state target_rank target_info target value =
      VH.replace state.sigma target value;
      trace_value state.queue.trace target_rank true;
      begin match target_info.readers with
        | None -> ()
        | Some readers ->
          defer_readers state readers;
          VH.clear readers
      end

    let[@inline always] try_dirty_read
        state owner_rank target_rank target_info target =
      if owner_rank <> target_rank
      && queue_side_dirty state.queue target_rank
      && VH.mem state.sigma target
      then
        match S.system target with
        | Some _ -> ()
        | None ->
          let old = VH.find state.sigma target in
          let candidate =
            S.Dom.join (start_value state target) target_info.side_aggregate
          in
          let was_controlled = target_info.controlled in
          if lattice_equal candidate old then begin
            target_info.started <- true;
            target_info.controlled <- true;
            queue_cancel state.queue target_rank
          end else if was_controlled then begin
            let _, next =
              U.update false target (U.initial_phase false target) old candidate
            in
            if S.Dom.leq old next then begin
              target_info.started <- true;
              target_info.controlled <- true;
              queue_cancel state.queue target_rank;
              if not (lattice_equal next old) then
                write_dirty_value state target_rank target_info target next
            end
          end else if S.Dom.leq old candidate then begin
            target_info.started <- true;
            target_info.controlled <- true;
            queue_cancel state.queue target_rank;
            write_dirty_value state target_rank target_info target candidate
          end

    let[@inline always] set_value state frame direct =
      flush_deferred state;
      let owner = frame.owner in
      let owner_info = frame.owner_info in
      let candidate =
        S.Dom.join direct
          (S.Dom.join (start_value state owner) owner_info.side_aggregate)
      in
      let old = VH.find state.sigma owner in
      let () =
        if not (lattice_equal candidate old) then begin
          let controlled =
            owner_info.controlled
          in
          if controlled then begin
            let next_phase, next =
              U.update false owner frame.owner_phase old candidate
            in
            frame.owner_phase <- next_phase;
            if not (lattice_equal next old) then begin
              write_changed_value state frame.owner_rank owner_info owner next;
              if Features.recompute_controlled then
                enqueue state owner
            end
          end else
            write_changed_value
              state frame.owner_rank owner_info owner candidate
        end
      in
      match state.queue.trace with
      | TraceDisabled -> ()
      | TraceEnabled _ ->
        let current = VH.find state.sigma owner in
        if lattice_equal current old then
          trace_value state.queue.trace frame.owner_rank false

    let solve xs roots _old_data =
      let state = create_state () in
      let pending_fifo = Stdlib.Queue.create () in
      let demanded = VH.create 16 in
      let defer_spawn target =
        if not (VH.mem demanded target) then begin
          VH.replace demanded target ();
          Stdlib.Queue.add target pending_fifo
        end
      in
      let pop_spawn () =
        Stdlib.Queue.take_opt pending_fifo
      in
      let dormant_stats_enabled =
        match Stdlib.Sys.getenv_opt "QSOLVER_DORMANT_STATS" with
        | None | Some "" -> false
        | Some _ -> true
      in
      let probes = ref 0 in
      let dormant_created = ref 0 in
      let effectful_promotions = ref 0 in
      let dormant_hits = ref 0 in
      let dormant_promotions = ref 0 in
      let[@inline always] bump counter =
        if dormant_stats_enabled then incr counter
      in

      let make_frame owner =
        let owner_rank, owner_info, _ = activate_rank state owner in
        owner_info.started <- true;
        {
          owner;
          owner_rank;
          owner_info;
          owner_phase = U.initial_phase false owner;
          outgoing_cells = None;
          local_side = None;
          previous_targets = None;
          current_targets = None;
          min_scope = owner, owner_rank;
        }
      in

      let prepare_evaluation frame owner_system count_evaluation =
        queue_note_evaluation state.queue frame.owner_rank;
        queue_clear_side_dirty state.queue frame.owner_rank;
        frame.min_scope <- frame.owner, frame.owner_rank;
        if Features.dead_side_elimination then begin
          frame.previous_targets <-
            begin match state.last_targets with
              | Some last_targets ->
                VH.find_option last_targets frame.owner
              | None -> None
            end;
          frame.current_targets <- None
        end;
        begin match frame.local_side with
          | Some local_side -> VH.clear local_side
          | None -> ()
        end;
        match owner_system with
        | Some _ ->
          trace_evaluation state.queue.trace frame.owner_rank;
          if count_evaluation then incr SolverStats.evals
        | None -> ()
      in

      let rec solve_episode owner =
        queue_enter_episode state.queue;
        let frame = make_frame owner in
        let owner_system = S.system owner in
        materialize state owner;
        evaluate_owner frame owner_system;
        reset_registered_cells state owner;
        queue_leave_episode state.queue

      and evaluate_owner frame owner_system =
        let owner_system_lookup _ = owner_system in
        Control.solve_one bottom
          (fun _ -> prepare_evaluation frame owner_system true)
          (fun _ -> get frame)
          (fun _ -> side frame)
          (fun _ -> spawn frame)
          (fun _ direct ->
             finish_evaluation frame;
             set_value state frame direct)
          (fun _ -> drain_episode frame owner_system)
          owner_system_lookup frame.owner

      and drain_episode frame owner_system =
        let next_rank = queue_max_rank state.queue in
        if frame.owner_rank <= next_rank then
          let next = queue_remove_max state.queue next_rank in
          if next_rank = frame.owner_rank then
            evaluate_owner frame owner_system
          else begin
            solve_episode next;
            drain_episode frame owner_system
          end

      (* Probe a completely fresh transfer before assigning a rank. A probe
          is promoted in place on its first callback, so an effectful transfer
          is never evaluated twice. *)
      and request_unranked variable =
        match VH.find_option state.dormant_bottom variable with
        | Some readers ->
          bump dormant_hits;
          Dormant readers
        | None ->
          bump probes;
          begin match S.system variable with
            | None ->
              bump dormant_created;
              let readers = VH.create 4 in
              VH.replace state.dormant_bottom variable readers;
              Dormant readers
            | Some body ->
              incr SolverStats.evals;
              let promoted = ref None in
              let promote () =
                match !promoted with
                | Some frame -> frame
                | None ->
                  bump effectful_promotions;
                  let frame = make_frame variable in
                  materialize state variable;
                  prepare_evaluation frame (Some body) false;
                  promoted := Some frame;
                  frame
              in
              let direct =
                body
                  (fun target -> get (promote ()) target)
                  (fun target raw -> side (promote ()) target raw)
                  (fun target -> spawn (promote ()) target)
              in
              begin match !promoted with
                | None ->
                  if lattice_equal direct bottom then begin
                    bump dormant_created;
                    let readers = VH.create 4 in
                    VH.replace state.dormant_bottom variable readers;
                    Dormant readers
                  end else begin
                    let frame = make_frame variable in
                    materialize state variable;
                    prepare_evaluation frame (Some body) false;
                    set_value state frame direct;
                    drain_episode frame (Some body);
                    reset_registered_cells state variable;
                    Promoted
                  end
                | Some frame ->
                  finish_evaluation frame;
                  set_value state frame direct;
                  drain_episode frame (Some body);
                  reset_registered_cells state variable;
                  Promoted
              end
          end

      and get frame target =
        let owner = frame.owner in
        let owner_rank = frame.owner_rank in
        match VH.find_option state.queue.ranks target with
        | None when not (VH.mem state.sigma target) ->
          begin match request_unranked target with
            | Dormant readers ->
              VH.replace readers owner ();
              bottom
            | Promoted -> get frame target
          end
        | possible_rank ->
          let target_rank, target_info =
            match possible_rank with
            | Some target_rank ->
              target_rank, DynArray.get state.queue.infos target_rank
            | None ->
              let target_rank, target_info, _ =
                activate_rank state target
              in
              target_rank, target_info
          in
          if owner_rank < target_rank
          && queue_force_side state.queue target_rank
          then solve_episode target;
          trace_get state.queue owner_rank target_rank;
          mark_controlled target_info target_rank owner_rank;
          try_dirty_read state owner_rank target_rank target_info target;
          let value =
            try VH.find state.sigma target with Not_found ->
              if owner_rank < target_rank then begin
                solve_episode target;
                VH.find state.sigma target
              end else begin
                enqueue state target;
                materialize state target;
                bottom
              end
          in
          mark_controlled target_info target_rank owner_rank;
          let _, old_min_rank = frame.min_scope in
          if target_rank < old_min_rank then
            frame.min_scope <- target, target_rank;
          VH.replace (readers_of_info target_info) owner ();
          value

      and side frame target raw =
        let local_side =
          match frame.local_side with
          | Some local_side -> local_side
          | None ->
            let local_side = VH.create 4 in
            frame.local_side <- Some local_side;
            local_side
        in
        let input, first_target_emission =
          match VH.find_option local_side target with
          | Some previous -> S.Dom.join previous raw, false
          | None -> raw, true
        in
        VH.replace local_side target input;
        if Features.dead_side_elimination && first_target_emission then begin
          let current_targets =
            match frame.current_targets with
            | Some current_targets -> current_targets
            | None ->
              let current_targets = VH.create 4 in
              frame.current_targets <- Some current_targets;
              current_targets
          in
          VH.replace current_targets target ()
        end;
        write_side_contribution frame target input

      and write_side_contribution frame target input =
        let source = frame.owner in
        let source_rank = frame.owner_rank in
        let target_rank, target_info, was_dormant =
          activate_rank state target
        in
        if was_dormant then bump dormant_promotions;
        trace_side state.queue source_rank target_rank;
        mark_controlled frame.owner_info source_rank target_rank;
        let scope, scope_rank = frame.min_scope in
        let old_aggregate = target_info.side_aggregate in
        let contributions =
          match target_info.contributions with
          | Some contributions -> contributions
          | None ->
            let contributions = VH.create 4 in
            target_info.contributions <- Some contributions;
            contributions
        in
        let old_contribution =
          VH.find_default contributions source bottom
        in
        let outgoing_cells =
          match frame.outgoing_cells with
          | Some outgoing_cells -> outgoing_cells
          | None ->
            let outgoing_cells = get_or_create state.side_cells source 4 in
            frame.outgoing_cells <- Some outgoing_cells;
            outgoing_cells
        in
        let cell =
          try VH.find outgoing_cells target with Not_found ->
            let fresh =
              {
                phase = U.initial_phase true target;
                reset_at = None;
                slot = reserve_slot target_info;
              }
            in
            VH.replace outgoing_cells target fresh;
            fresh
        in
        let phase = cell.phase in
        let next_phase, next_contribution =
          side_update source target phase
            old_contribution input old_aggregate
        in
        VH.replace contributions source next_contribution;
        register_reset state source target target_rank
          scope scope_rank cell next_phase;
        let next_aggregate, aggregate_changed =
          if Config.aggregate_cache then begin
            let aggregate = match cached_aggregate state target target_info contributions cell
                                    old_contribution next_contribution with
            | Some aggregate -> aggregate
            | None -> if S.Dom.leq next_contribution old_aggregate then old_aggregate
              else S.Dom.join old_aggregate next_contribution in
            JoinTree.publish_update old_aggregate aggregate
          end else
          if S.Dom.leq old_contribution next_contribution then
            if S.Dom.leq next_contribution old_aggregate
            then old_aggregate, false
            else S.Dom.join old_aggregate next_contribution, true
          else begin
            let next_aggregate = recompute_aggregate contributions in
            next_aggregate,
            not (lattice_equal next_aggregate old_aggregate)
          end
        in
        if aggregate_changed then
          target_info.side_aggregate <- next_aggregate;
        if was_dormant then begin
          (* Its certified direct RHS is bottom and it had no outgoing
              effects, so the aggregate is already its complete value. *)
          target_info.started <- true;
          materialize state target;
          if aggregate_changed then
            write_changed_value state target_rank target_info
              target next_aggregate
        end else if aggregate_changed then begin
          queue_mark_side_dirty state.queue target_rank;
          if source_rank < target_rank
          && not (VH.mem state.sigma target)
          && not queue_defer_side_stabilization
          then
            solve_episode target
          else
            enqueue_side state target
        end

      and finish_evaluation frame =
        if Features.dead_side_elimination then begin
          begin match frame.previous_targets with
            | None -> ()
            | Some previous_targets ->
              VH.iter
                (fun target () ->
                   let current =
                     match frame.current_targets with
                     | Some current_targets -> VH.mem current_targets target
                     | None -> false
                   in
                   if not current then
                     write_side_contribution frame target bottom)
                previous_targets
          end;
          begin match state.last_targets, frame.current_targets with
            | Some last_targets, Some current_targets ->
              VH.replace last_targets frame.owner current_targets
            | None, Some current_targets ->
              let last_targets = VH.create 32 in
              state.last_targets <- Some last_targets;
              VH.replace last_targets frame.owner current_targets
            | Some last_targets, None ->
              VH.remove last_targets frame.owner
            | None, None -> ()
          end
        end

      and spawn frame target =
        if Features.defer_spawns then defer_spawn target
        else spawn_immediate frame target

      and spawn_immediate frame target =
        let owner_rank = frame.owner_rank in
        match VH.find_option state.queue.ranks target with
        | None when not (VH.mem state.sigma target) ->
          ignore (request_unranked target)
        | possible_rank ->
          let target_rank =
            match possible_rank with
            | Some target_rank -> target_rank
            | None ->
              let target_rank, _, _ = activate_rank state target in
              target_rank
          in
          if not (VH.mem state.sigma target) then
            if owner_rank < target_rank then
              solve_episode target
            else begin
              enqueue state target;
              materialize state target
            end
      in

      List.iter
        (fun (variable, input) ->
           let start = S.Dom.join (start_value state variable) input in
           VH.replace state.starts variable start;
           VH.replace state.sigma variable start)
        xs;
      let is_started variable =
        match VH.find_option state.dormant_bottom variable with
        | Some _ -> true
        | None -> seed_started state.queue variable
      in
      let solve_requested variable =
        match VH.find_option state.queue.ranks variable with
        | Some _ -> solve_episode variable
        | None when VH.mem state.sigma variable -> solve_episode variable
        | None -> ignore (request_unranked variable)
      in
      solve_initial state.queue is_started solve_requested roots xs;
      (* Drain ordinary work completely before selecting the next deferred demand.
         A real read still solves its target immediately through the normal get. *)
      let rec drain_spawns () =
        match pop_spawn () with
        | None -> ()
        | Some target ->
          solve_initial state.queue is_started solve_requested [target] [];
          drain_spawns ()
      in
      drain_spawns ();
      if dormant_stats_enabled then
        Stdlib.Printf.eprintf
          "%s probes=%d dormant=%d effectful=%d hits=%d promotions=%d remaining=%d\n%!"
          SidePolicy.stats_name !probes !dormant_created
          !effectful_promotions !dormant_hits !dormant_promotions
          (VH.length state.dormant_bottom);
      finish_trace state.queue;
      SolverStats.vars := !SolverStats.vars + VH.length state.sigma;
      state.sigma, ()
  end

